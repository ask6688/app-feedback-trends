def judge_risk(text, domain="market"):

    if "和谐版" in text and not re.search(r"(被|给|遭|全|都)?和谐(了|掉|没|完)", text):
        return False, "「和谐版」指第三方修改版，非资源风控"
    if re.search(r"(没被封|没有被封|从未被封|从没被封|不会封|不封|没封)", text):
        return False, "表述为「未被封」，非封禁类风控反馈"
    if re.search(r"(苹果|app\s?store|应用商店|应用市场|市场|小米|华为|荣耀|oppo|vivo|酷安)[^。，,！!？?]{0,12}审核", text, re.I):
        return False, "「审核」指向应用商店上架审核，非资源内容风控"
    if re.search(r"审核[^。，,！!？?]{0,8}(机制|商店|市场|上架)", text):
        return False, "「审核」指向应用商店上架审核，非资源内容风控"
    if re.search(r"(挂|外挂|开挂|脚本|辅助|游戏|吃鸡|王者|和平精英|三角洲|小熊猫)[^。，,！!？?]{0,12}(被封|封号|封禁|封了)", text):
        return False, "「封」指向游戏账号封禁，非资源风控"
    if re.search(r"违规(营销|推广|广告|收费|扣费|经营|宣传)", text) and not any(w in text for w in RISK_HARD):
        return False, "「违规」修饰平台经营行为，非资源内容风控"

    takedown = RISK_TAKEDOWN_RE.search(text)
    if not takedown and any(w in text for w in RISK_EXCLUDE_CTX) \
            and not any(w in text for w in RISK_HARD):
        return False, "「下架」为对应用本身的评价诉求，不属于资源风控策略"

    hit = [w for w in RISK_STRONG if w in text]
    if not hit:
        if takedown:
            return True, "「%s%s」属于资源被下架/下线/移除类风控策略" % (
                takedown.group(1), takedown.group(2))
        return False, "无资源审核/违规/封禁/屏蔽类表述"

    if set(hit) == {"屏蔽"} and re.search(r"屏蔽[^。，,！!？?]{0,6}(广告|弹窗|通知|推送)", text):
        return False, "「屏蔽」指向屏蔽广告/通知，非资源风控"
    if set(hit) == {"审核"}:
        if domain == "cs" and CS_RISK_AUDIT_CTX.search(text) and not CS_RISK_AUDIT_KEEP.search(text):
            return False, "「审核」指向账号注销/退款/实名等业务审核流程，非资源内容风控"
        return True, "提及内容/资源审核流程，属于风控策略"
    if set(hit) == {"涉嫌"} and not any(w in text for w in ["违规", "侵权", "版权", "资源"]):
        return False, "「涉嫌」未指向资源违规"
    return True, "提及「%s」，属于资源违规、屏蔽、封禁或失效类风控策略" % hit[0]

def judge_ad(text, domain="market"):

    has_ad_complaint = bool(AD_COMPLAINT_RE.search(text))
    if not has_ad_complaint:
        for p in AD_NEG_PHRASES:
            if p in text:
                return False, "命中精确否定/正面短语「%s」，不作为广告反馈" % p
    strong = [w for w in AD_STRONG if w in text]
    if strong:

        if (domain == "cs" and set(strong) <= {"弹窗", "广告弹出"}
                and CS_AD_POP_PAY.search(text) and "广告" not in text):
            return False, "「弹窗」指向扣费/支付类弹窗，非广告干扰"
        return True, "提及「%s」，属于广告相关反馈" % strong[0]
    m = AD_POP_RE.search(text)
    if m:
        seg = text[max(0, m.start() - 12): m.end() + 12]
        if AD_POP_EXCLUDE_RE.search(seg):
            return False, "「弹出」指向会员/开通付费界面，属于收费类而非广告"
        return True, "出现「%s」，属于弹窗推广类广告干扰" % m.group(0)[:12]
    if JUMP_RE.search(text):
        j = JUMP_RE.search(text).group(0)
        f = JUMP_FORCE_RE.search(text)
        if f:
            if domain == "cs" and not CS_AD_JUMP_STRONG.search(text):

                if CS_AD_JUMP_STORE.search(text):
                    return False, "「跳转」指向应用商店/浏览器等正常跳转，非广告干扰"
                return False, "仅「跳转+%s」，无广告/误触/第三方语境，不定为广告" % f.group(0)[:6]
            return True, "出现「%s + %s」，属于强制跳转类广告干扰" % (j, f.group(0)[:8])
        return False, "仅提及「%s」但无强制/误导语境，不定为广告" % j
    return False, "无广告相关表述"

def judge_dl(text, domain="market"):
    for p in DL_EXCLUDE_RE:
        if p.search(text):
            return False, "「下载」指向对应用本身的劝退/动作描述，非下载体验问题"
    if DL_SPEED_RE.search(text):
        m = DL_SPEED_RE.search(text)
        return True, "出现速度受限/异常表述「%s」，属于下载体验问题" % m.group(0)[:12]
    if DL_FAIL_RE.search(text):
        m = DL_FAIL_RE.search(text)
        return True, "出现下载失败/中断类表述「%s」，属于下载体验问题" % m.group(0)[:14]
    v = DL_VERB_RE.search(text)
    if v:
        q = DL_QUALITY_RE.search(text)
        if q:
            return True, "在「%s」语境下出现「%s」，属于下载体验问题" % (v.group(0), q.group(0))
        return False, "仅提及「%s」，未描述下载速度/失败/中断等体验问题" % v.group(0)
    return False, "无下载相关表述"

